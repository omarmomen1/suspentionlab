"""
tests/test_rls_isolation.py  (Wave 6, prompt section 1)

Automated PostgreSQL Row-Level Security isolation tests:
  1. Cross-tenant queries cannot leak rows under FORCE ROW LEVEL SECURITY.
  2. The application DB role does not rely on superuser / BYPASSRLS:
     isolation is verified while running as an unprivileged NOSUPERUSER,
     NOBYPASSRLS role, and that role's pg_roles flags are asserted.

Requires a real PostgreSQL instance (testcontainers). Skips cleanly in
environments without Docker / testcontainers.
"""

import uuid

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine


TEAM_A = uuid.uuid4()
TEAM_B = uuid.uuid4()
APP_ROLE = "rls_wave6_app_role"
TABLE = "rls_wave6_probe"


@pytest.fixture
async def pg_engine(postgres_container):
    if postgres_container is None:
        pytest.skip("testcontainers/Docker unavailable: RLS isolation tests require real PostgreSQL")
    engine = create_async_engine(postgres_container.get_connection_url())
    yield engine
    await engine.dispose()


async def _setup_probe_table(engine):
    """Create an unprivileged app role and an RLS-protected probe table seeded
    with rows for two tenants. Mirrors the policy shape generated by
    backend/database/rls.py for team-owned tables."""
    async with engine.begin() as conn:
        await conn.execute(text(f'DROP TABLE IF EXISTS {TABLE} CASCADE'))
        await conn.execute(text(f'DROP ROLE IF EXISTS {APP_ROLE}'))
        await conn.execute(text(f'CREATE ROLE {APP_ROLE} LOGIN NOSUPERUSER NOBYPASSRLS'))
        await conn.execute(text(
            f'CREATE TABLE {TABLE} (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), '
            f'team_id uuid NOT NULL, payload text NOT NULL)'
        ))
        await conn.execute(text(f'ALTER TABLE {TABLE} ENABLE ROW LEVEL SECURITY'))
        await conn.execute(text(f'ALTER TABLE {TABLE} FORCE ROW LEVEL SECURITY'))
        await conn.execute(text(
            f"CREATE POLICY {TABLE}_tenant_isolation_policy ON {TABLE} FOR ALL USING ("
            f"team_id = NULLIF(current_setting('app.current_tenant_id', true), '')::uuid"
            f") WITH CHECK ("
            f"team_id = NULLIF(current_setting('app.current_tenant_id', true), '')::uuid)"
        ))
        await conn.execute(text(f'GRANT SELECT, INSERT ON {TABLE} TO {APP_ROLE}'))
        # Seed as the container superuser (RLS does not apply to superuser):
        # 2 rows for tenant A, 1 row for tenant B
        await conn.execute(text(
            f"INSERT INTO {TABLE} (team_id, payload) VALUES "
            f"('{TEAM_A}', 'a1'), ('{TEAM_A}', 'a2'), ('{TEAM_B}', 'b1')"
        ))


@pytest.mark.asyncio
async def test_cross_tenant_queries_cannot_leak_rows(pg_engine):
    await _setup_probe_table(pg_engine)
    async with pg_engine.begin() as conn:
        # Run as the unprivileged application role (no superuser bypass)
        await conn.execute(text(f'SET ROLE {APP_ROLE}'))

        # Tenant A context: sees exactly its own 2 rows
        await conn.execute(text(f"SET LOCAL app.current_tenant_id = '{TEAM_A}'"))
        rows_a = (await conn.execute(text(f'SELECT payload FROM {TABLE} ORDER BY payload'))).fetchall()
        assert [r[0] for r in rows_a] == ['a1', 'a2']

    async with pg_engine.begin() as conn:
        await conn.execute(text(f'SET ROLE {APP_ROLE}'))
        # Tenant B context: sees exactly its own 1 row — no cross-tenant leak
        await conn.execute(text(f"SET LOCAL app.current_tenant_id = '{TEAM_B}'"))
        rows_b = (await conn.execute(text(f'SELECT payload FROM {TABLE}'))).fetchall()
        assert [r[0] for r in rows_b] == ['b1']

    async with pg_engine.begin() as conn:
        await conn.execute(text(f'SET ROLE {APP_ROLE}'))
        # No tenant context at all: sees nothing
        await conn.execute(text("SET LOCAL app.current_tenant_id = ''"))
        rows_none = (await conn.execute(text(f'SELECT payload FROM {TABLE}'))).fetchall()
        assert rows_none == []


@pytest.mark.asyncio
async def test_application_role_is_not_superuser_and_cannot_bypass_rls(pg_engine):
    await _setup_probe_table(pg_engine)
    async with pg_engine.begin() as conn:
        flags = (await conn.execute(text(
            "SELECT rolsuper, rolbypassrls FROM pg_roles WHERE rolname = current_user"
        ))).fetchone()
        role_flags = (await conn.execute(text(
            f"SELECT rolsuper, rolbypassrls FROM pg_roles WHERE rolname = '{APP_ROLE}'"
        ))).fetchone()
        # The application role must not carry superuser or BYPASSRLS
        assert role_flags is not None
        assert role_flags[0] is False, "application role must be NOSUPERUSER"
        assert role_flags[1] is False, "application role must be NOBYPASSRLS"

        # Table must have RLS enabled AND forced (forced = even the owner is subject)
        rel = (await conn.execute(text(
            "SELECT c.relrowsecurity, c.relforcerowsecurity FROM pg_class c "
            f"JOIN pg_namespace n ON n.oid = c.relnamespace "
            f"WHERE c.relname = '{TABLE}' AND n.nspname = 'public'"
        ))).fetchone()
        assert rel == (True, True)


@pytest.mark.asyncio
async def test_rls_ddl_covers_all_tenant_tables():
    """Pure-DDL check (no DB needed): every tenant-owned table gets ENABLE +
    FORCE RLS and a tenant isolation policy."""
    from suspensionlab.backend.database.rls import TENANT_TABLES, generate_table_rls_sql

    assert len(TENANT_TABLES) >= 10
    for table in TENANT_TABLES:
        stmts = generate_table_rls_sql(table)
        joined = " ".join(stmts)
        assert f"ALTER TABLE IF EXISTS {table} ENABLE ROW LEVEL SECURITY" in joined
        assert f"ALTER TABLE IF EXISTS {table} FORCE ROW LEVEL SECURITY" in joined
        assert f"CREATE POLICY {table}_tenant_isolation_policy" in joined
