import { describe, it, expect, vi, beforeEach } from "vitest";
import {
  CaeApi,
  SearchApi,
  TimelineDecisionApi,
  CaeImportRequest,
} from "../lib/api_client";
import * as apiModule from "../lib/api";
import { parseEngineeringError } from "../components/sim/EngineeringErrorDisplay";
